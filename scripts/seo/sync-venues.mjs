// Copies researched venue JSON (status "ok") into content/venues/ and regenerates src/lib/venues-data.ts.
//   node scripts/seo/sync-venues.mjs [sourceDir]
// Without sourceDir it only regenerates venues-data.ts from content/venues/.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT_DIR = path.join(ROOT, "content/venues");
const src = process.argv[2];

// Venues whose researched location is closer to a different city page than first assumed.
const CITY_OVERRIDES = { "castle-ladyhawke": "waynesville" };
const KEEP = ["slug", "name", "citySlug", "tier", "town", "state", "address", "title", "description", "h1", "lede", "facts", "sections", "faq", "sources", "asOf"];

if (src) {
  for (const f of fs.readdirSync(src).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(fs.readFileSync(path.join(src, f), "utf8"));
    if (d.status !== "ok") {
      console.log(`skip ${d.slug}: ${d.status}`);
      continue;
    }
    if (CITY_OVERRIDES[d.slug]) d.citySlug = CITY_OVERRIDES[d.slug];
    const clean = Object.fromEntries(KEEP.map((k) => [k, d[k] ?? null]));
    clean.facts = (d.facts || []).map(({ label, value }) => ({ label, value }));
    fs.writeFileSync(path.join(OUT_DIR, `${d.slug}.json`), JSON.stringify(clean, null, 2) + "\n");
  }
}

const files = fs.readdirSync(OUT_DIR).filter((f) => f.endsWith(".json")).sort();
const ident = (f) => "v_" + f.replace(/\.json$/, "").replace(/[^a-z0-9]/gi, "_");
const ts = [
  "// Generated by scripts/seo/sync-venues.mjs from content/venues/*.json. Edit the JSON, then rerun.",
  'import type { Venue } from "./venues";',
  ...files.map((f) => `import ${ident(f)} from "../../content/venues/${f}";`),
  "",
  `export const VENUES_DATA: Venue[] = [${files.map(ident).join(", ")}] as Venue[];`,
  "",
].join("\n");
fs.writeFileSync(path.join(ROOT, "src/lib/venues-data.ts"), ts);
console.log(`${files.length} venues -> src/lib/venues-data.ts`);
